"""---
## Part 6: Replenishment Simulation
### Task 6.1: From forecast to decision
We compare four ways of choosing how much stock to prepare for each product-day:

| Policy | Stock level |
|---|---|
| P1 | Point forecast |
| P2 | Point forecast + one standard deviation of calibration errors (fixed safety stock) |
| P3 | Upper end of the 90% conformal interval |
| P4 | P3, plus 20% extra for 7 days after the actual sales fell outside the 90% interval (uses past days only; these alerts are not the synthetic anomalies of Part 5b) |

**Metrics:** fill rate (share of demand met), share of days with a stock-out, and average overstock in units.

**Replenishment priority:** `(upper bound - forecast) x price` highlights products with the widest uncertainty and highest value at risk. Because products in the same volume group share the same interval width, this score is effectively (group width x price), so ties are common and it does not capture item-specific uncertainty.

**Simplifications:** no order lead time, no inventory carry-over between days, stock levels are not rounded to whole units, the simulation uses the actual (un-injected) sales, and test-window zeros caused by real stock-outs are not removed, so true demand may be slightly under-estimated.

**In our run:**

| Policy | Fill rate | Stockout days % | Avg overstock | Total cost (illustrative) |
|---|---|---|---|---|
| P1 | 0.777 | 36.4 | 1.28 | 19346 |
| P2 | 0.931 | 12.2 | 3.21 | 20447 |
| P3 | 0.963 | 5.9 | 4.71 | 26353 |
| P4 | 0.977 | 4.1 | 5.35 | 28886 |

A higher fill rate always comes with more overstock. The biggest gain comes from adding a basic safety stock (P1 to P2).
"""

a["recent_alert"] = a.groupby("item_id").alert_true.transform(
    lambda s: s.shift(1).rolling(7, min_periods=1).max().fillna(0))

a["stock_P1"] = a.pred_gbm
a["stock_P2"] = a.pred_gbm + a.item_id.map(sd).fillna(sd.mean())
a["stock_P3"] = a.hi
a["stock_P4"] = np.where(a.recent_alert == 1, a.hi * 1.2, a.hi)

