"""---
## Part 7: Rolling-Origin Validation
All results so far come from one 28-day test window. To check that they are not a coincidence, we repeat the whole procedure on **five consecutive 28-day windows**, moving backwards in time. For each window, the models and conformal intervals are re-trained using only data from before that window.

**In our run (5-fold mean, standard deviation in brackets):**

| | Naive | Linear Regression | LightGBM |
|---|---|---|---|
| RMSE | 3.698 (0.097) | 3.069 (0.085) | 3.164 (0.191) |
| RMSSE | 0.859 (0.021) | 0.743 (0.014) | 0.692 (0.023) |

Conformal coverage averages 0.903 (std 0.010). Both learned models beat the baseline in every window; LightGBM has the best RMSSE in all five windows, while linear regression has the best RMSE in three of five.

**Limitation:** all five windows lie between January and May 2016, so full-year seasonality is not tested. Earlier windows also have less training data.
"""

from sklearn.linear_model import LinearRegression
import lightgbm as lgb
N_FOLDS = 5   # 5 rolling windows of 28 days, moving backwards from the end of the data
LR_FEATS = [f for f in FEATS if f != "item_code"]
ok_all = ~long.stockout_zero & ~long.not_listed
rows = []
for k in range(N_FOLDS):
    te_start = n_days - TEST_LEN * (k + 1) + 1
    te_end = te_start + TEST_LEN - 1
    ca_start = te_start - CAL_LEN
    tr = long[(long.t < ca_start) & ok_all].dropna(subset=["lag28"]).copy()
    ca = long[(long.t >= ca_start) & (long.t < te_start) & ok_all].dropna(subset=["lag28"]).copy()
    te = long[(long.t >= te_start) & (long.t <= te_end)].dropna(subset=["lag7"]).copy()

    fill_k = tr[LR_FEATS].median()
    lr_k = LinearRegression().fit(tr[LR_FEATS].fillna(fill_k), tr.y)
    gbm_k = lgb.LGBMRegressor(n_estimators=600, learning_rate=0.05, num_leaves=63, subsample=0.8,
                              colsample_bytree=0.8, subsample_freq=1, random_state=42, verbose=-1)
    gbm_k.fit(tr[FEATS], tr.y)
    for d in (ca, te):
        d["p_naive"] = d["lag7"]
        d["p_lr"] = np.clip(lr_k.predict(d[LR_FEATS].fillna(fill_k)), 0, None)
        d["p_gbm"] = np.clip(gbm_k.predict(d[FEATS]), 0, None)

    sc = tr.groupby("item_id")["y"].apply(lambda s: np.mean(np.diff(s.values) ** 2)).replace(0, np.nan)
    def ev(df, col):
        e = df.y - df[col]
        rmsse = np.sqrt(((e ** 2).groupby(df.item_id).mean() / sc.reindex(df.item_id.unique())).mean())
        return np.sqrt((e ** 2).mean()), rmsse

    # Conformal coverage for this fold (volume-group calibration, as before)
    vg = pd.qcut(tr.groupby("item_id").y.mean(), 3, labels=[0, 1, 2])
    ca["vg"] = ca.item_id.map(vg).astype(int); te["vg"] = te.item_id.map(vg).astype(int)
    ca["score"] = (ca.y - ca.p_gbm).abs()
    qk = ca.groupby("vg")["score"].apply(lambda s: np.sort(s.values)[min(int(np.ceil((len(s) + 1) * 0.9)), len(s)) - 1])
    qq = te.vg.map(qk)
    cover = ((te.y >= te.p_gbm - qq) & (te.y <= te.p_gbm + qq)).mean()

    row = {"Fold": k + 1, "Test window (d_)": f"{te_start}-{te_end}", "Test start date": te.date.min().date()}
    for nm, col in [("Naive", "p_naive"), ("LinReg", "p_lr"), ("LightGBM", "p_gbm")]:
        r, s = ev(te, col)
        row["RMSE " + nm] = r; row["RMSSE " + nm] = s
    row["Conformal coverage"] = cover
    rows.append(row)
    print("fold", k + 1, "done", flush=True)

cv = pd.DataFrame(rows).set_index("Fold")
print(cv.round(3).to_string())
num = cv.select_dtypes("number")
summary = pd.DataFrame({"mean": num.mean(), "std": num.std()})
print(); print(summary.round(3).to_string())
