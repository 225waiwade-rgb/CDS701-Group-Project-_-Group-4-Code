"""---
## Part 5: Prediction Intervals and Anomaly Alerting
### Task 5.1: Conformal Prediction Intervals
A point forecast ("we expect to sell 50") says nothing about risk. **Split conformal prediction** adds a range around each forecast with a guaranteed long-run coverage.

**How it works**
1. Take the model's absolute errors on the calibration window.
2. For a 90% interval, take the error value that 90% of calibration errors fall below.
3. Add and subtract this value from every forecast.

Errors grow with sales volume, so we calibrate separately for three volume groups (low, mid, high). The method needs no retraining and works with any model.

**What to check:** coverage (the share of actual values inside the interval, target 0.90) and average interval width.

**In our run:** half-widths are about 1.83 / 3.17 / 7.39 units for low / mid / high volume. Overall coverage is 0.895. Coverage is lower on weekends (0.852) and holidays (0.879), which means intervals are too narrow on those days.
"""

ALPHA = 0.10   # target: 90% of actual values should fall inside the interval

# Group items by average sales volume (3 groups), so each group gets its own interval width
item_mean = train.groupby("item_id").y.mean()
vol_group = pd.qcut(item_mean, 3, labels=[0, 1, 2])
for d in (calib, test):
    d["vgrp"] = d.item_id.map(vol_group).astype(int)

# Calibration: absolute errors of LightGBM on the calibration window
calib["score"] = (calib.y - calib.pred_gbm).abs()

def conformal_q(s, alpha=ALPHA):
    n = len(s); k = min(int(np.ceil((n + 1) * (1 - alpha))), n)
    return np.sort(s.values)[k - 1]

q = calib.groupby("vgrp")["score"].apply(conformal_q)
print("Interval half-width per volume group (low, mid, high):", q.round(2).tolist())

test["q"] = test.vgrp.map(q)
test["lo"] = (test.pred_gbm - test.q).clip(lower=0)
test["hi"] = test.pred_gbm + test.q
test["covered"] = ((test.y >= test.lo) & (test.y <= test.hi)).astype(int)

rows = []
for name, mask in define_strata(test).items():
    sub = test[mask]
    rows.append({"Stratum": name, "n": len(sub), "Coverage": sub.covered.mean(), "Avg width": (sub.hi - sub.lo).mean()})
cov = pd.DataFrame(rows).set_index("Stratum")
print("Target coverage:", 1 - ALPHA)
print(cov.round(3).to_string())
cov.to_csv("conformal_coverage.csv")

hi_item = test.groupby("item_id").y.sum().idxmax()
low_pool = test[test.vgrp == 0].groupby("item_id").y.apply(lambda s: (s > 0).sum())
lo_item = low_pool.idxmax()
fig, axes = plt.subplots(1, 2, figsize=(13, 4.5), sharex=True)
for ax, item, label in [(axes[0], hi_item, "High-volume product"), (axes[1], lo_item, "Low-volume product")]:
    s = test[test.item_id == item].sort_values("t")
    ax.fill_between(s.date, s.lo, s.hi, color=COLORS["LightGBM"], alpha=0.25, label="90% interval")
