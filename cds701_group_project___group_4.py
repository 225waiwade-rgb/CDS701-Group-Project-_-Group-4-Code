"""### Task 5.2: Anomaly Alerting
**Goal:** raise an alert when actual sales differ strongly from what the model expected.

**Important:** real M5 data contain no anomaly labels. To measure detection quality we **inject synthetic anomalies** into 5% of test rows: half are demand surges (actual sales x 2.5, rounded) and half are drops to zero. Results therefore show how well each rule can find *simulated* anomalies, not real events.

| Rule | Idea |
|---|---|
| Interval | Alert if the actual value falls outside the 90% interval |
| z-score | Alert if the standardized error exceeds 3 |
| EWMA | Alert on a smoothed, persistent drift of the error |
| CUSUM | Alert when small errors accumulate in one direction |

**In our run:**

| Rule | Recall | Precision | False alarm rate |
|---|---|---|---|
| Interval | 0.409 | 0.168 | 0.106 |
| z-score | 0.198 | 0.443 | 0.013 |
| EWMA | 0.144 | 0.120 | 0.056 |
| CUSUM | 0.156 | 0.175 | 0.039 |

The interval rule finds the most anomalies but gives the most false alarms; z-score is the most precise but misses more. EWMA and CUSUM are designed for sustained drifts, so they are weaker against single-day spikes.

**Caveats:** (1) The four rules use different thresholds, so they sit at different false-alarm levels (about 10% for the interval rule vs. about 1% for z-score); recall and precision are therefore not directly comparable. (2) Anomalies are injected only where actual sales > 0; surges on products selling 1-2 units and drops to zero on slow products are almost indistinguishable from normal demand, which caps recall for every rule. (3) Only 5% of rows are positive (257 of 5152), which lowers precision.
"""

rng = np.random.default_rng(42)
a = test.sort_values(["item_id", "t"]).reset_index(drop=True).copy()

a["label"] = 0
cand = a.index[a.y > 0].to_numpy()
pick = rng.choice(cand, int(0.05 * len(a)), replace=False)
a.loc[pick, "label"] = 1
surge = rng.random(len(a)) < 0.5

a["yobs"] = a.y.astype(float)
a.loc[(a.label == 1) & surge, "yobs"] = (a.y * 2.5).round()
a.loc[(a.label == 1) & ~surge, "yobs"] = 0

sd = (calib.y - calib.pred_gbm).groupby(calib.item_id).std().fillna((calib.y - calib.pred_gbm).std())
a["z"] = (a.yobs - a.pred_gbm) / a.item_id.map(sd).replace(0, np.nan).fillna(1)

a["alert_interval"] = ((a.yobs > a.hi) | (a.yobs < a.lo)).astype(int)
a["alert_z"] = (a.z.abs() > 3).astype(int)
a["ewma"] = a.groupby("item_id").z.transform(lambda s: s.ewm(alpha=0.3).mean())
a["alert_ewma"] = (a.ewma.abs() > 1.5).astype(int)

def cusum_alerts(s, k=0.5, h=4):
    pos = neg = 0
    out = []
    for v in s.values:
        pos = max(0, pos + v - k)
        neg = max(0, neg - v - k)
        hit = int(pos > h or neg > h)
        out.append(hit)
        if hit:
            pos = neg = 0
    return pd.Series(out, index=s.index)

a["alert_cusum"] = a.groupby("item_id").z.transform(cusum_alerts)

from sklearn.metrics import confusion_matrix
res = {}
for name in ["alert_interval", "alert_z", "alert_ewma", "alert_cusum"]:
    tn, fp, fn, tp = confusion_matrix(a.label, a[name], labels=[0, 1]).ravel()
    res[name] = {"TP": tp, "FP": fp, "FN": fn, "TN": tn,
                 "Recall": tp / max(tp + fn, 1), "Precision": tp / max(tp + fp, 1),
                 "False alarm rate": fp / max(fp + tn, 1)}
anom = pd.DataFrame(res).T
print(anom.round(3).to_string())
anom.to_csv("anomaly_eval.csv")

# Alerts on the actual series, used only by the Part 6 simulation
a["alert_true"] = ((a.y > a.hi) | (a.y < a.lo)).astype(int)

import numpy as np
an = anom[["Recall", "Precision", "False alarm rate"]].astype(float)
an.index = ["Outside interval", "z-score", "EWMA", "CUSUM"]
x = np.arange(len(an)); w = 0.26
fig, ax = plt.subplots(figsize=(10, 4.8))
