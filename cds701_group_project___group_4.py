"""---
## Part 8: Exploratory Extension - Volume-Based Model Router
**Idea:** Part 4 suggests LightGBM is better for low-volume products and linear regression for high-volume products. A *router* assigns each volume group to one of the two models.

Two variants are tested:
1. **Router chosen on the calibration window.** For each volume group, pick the model with the lower calibration RMSE. The test window is never used to make the choice, so this is the fair version.
2. **Fixed rule.** Low and mid volume use LightGBM, high volume uses linear regression. This rule was proposed *after* seeing earlier test results, so its score is optimistic.

**In our run:**

| Model | RMSE | MAE | RMSSE |
|---|---|---|---|
| LightGBM | 3.210 | 2.103 | 0.723 |
| Router (calibration) | 3.210 | 2.103 | 0.723 |
| Fixed rule | 3.030 | 1.896 | 0.717 |

The calibration-based router selected LightGBM in all groups, so it equals plain LightGBM. The fixed rule is best on all three metrics, but the gain over the best single model is small and has not been validated on independent data. We treat this as an idea for future work, not as a proven improvement.
"""

